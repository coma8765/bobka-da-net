DROP TABLE IF EXISTS deliveries;
DROP TABLE IF EXISTS warehouse_sections;
DROP TABLE IF EXISTS warehouses;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS suppliers;

CREATE TABLE suppliers (
    supplier_id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(120) NOT NULL,
    tax_id varchar(12) NOT NULL,
    country varchar(80) NOT NULL,
    city varchar(80) NOT NULL,
    email varchar(160) NOT NULL,
    phone varchar(24) NOT NULL,
    rating numeric(3, 2) NOT NULL,
    is_active boolean NOT NULL,
    created_at date NOT NULL
);

CREATE TABLE products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY,
    sku varchar(20) NOT NULL,
    name varchar(160) NOT NULL,
    category varchar(80) NOT NULL,
    unit varchar(12) NOT NULL,
    unit_price numeric(12, 2) NOT NULL,
    weight_kg numeric(10, 3) NOT NULL,
    is_perishable boolean NOT NULL,
    created_at date NOT NULL
);

CREATE TABLE warehouses (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY,
    code varchar(16) NOT NULL,
    name varchar(160) NOT NULL,
    country varchar(80) NOT NULL,
    city varchar(80) NOT NULL,
    address varchar(240) NOT NULL,
    opened_on date NOT NULL
);

CREATE TABLE warehouse_sections (
    section_id bigint GENERATED BY DEFAULT AS IDENTITY,
    warehouse_id bigint NOT NULL,
    parent_section_id bigint,
    code varchar(24) NOT NULL,
    name varchar(160) NOT NULL,
    section_type varchar(20) NOT NULL,
    capacity_m3 numeric(10, 2) NOT NULL,
    floor smallint NOT NULL,
    is_active boolean NOT NULL
);

CREATE TABLE deliveries (
    delivery_id bigint GENERATED BY DEFAULT AS IDENTITY,
    supplier_id bigint NOT NULL,
    product_id bigint NOT NULL,
    warehouse_id bigint NOT NULL,
    delivered_at timestamp without time zone NOT NULL,
    quantity integer NOT NULL,
    unit_cost numeric(12, 2) NOT NULL,
    batch_number varchar(20) NOT NULL,
    quality_status varchar(16) NOT NULL,
    expires_on date
);
